/**
 * B1 questions for the level test. There are no B1 topic pages yet, so each question is its own group:
 * the test draws a few of them per attempt. Prompts are Estonian sentences with a gloss in brackets.
 */
type Text = [ru: string, en: string, et: string];

const b1 = (group: string, prompt: Text, options: L[], answer: number, explain: Text): Question & { group: string } => ({
  level: 'B1',
  group,
  prompt: tr(...prompt),
  options,
  answer,
  explain: tr(...explain),
});

const typedB1 = (group: string, prompt: Text, accept: string[], explain: Text): Question & { group: string } => ({
  level: 'B1',
  group,
  prompt: tr(...prompt),
  options: [],
  answer: -1,
  accept,
  explain: tr(...explain),
});

